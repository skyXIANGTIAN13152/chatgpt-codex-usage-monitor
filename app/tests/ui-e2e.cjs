'use strict';
const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.resolve(root, '..', 'qa');
fs.mkdirSync(output, {recursive:true});
const data = fs.mkdtempSync(path.join(output, 'ui-data-'));
const env = {...process.env}; delete env.ELECTRON_RUN_AS_NODE;
(async()=>{
  let app; const errors=[];
  try {
    app=await electron.launch({executablePath:require('electron'),args:[root,'--test-data-dir',data,'--no-providers'],env,cwd:root});
    const page=await app.firstWindow();
    page.on('pageerror',e=>errors.push(e.message));
    await page.getByRole('button',{name:'使用 ChatGPT 账号登录',exact:true}).waitFor();
    await page.getByRole('button',{name:'使用 Claude Code 账号登录',exact:true}).waitFor();
    assert.deepEqual(await page.evaluate(()=>[innerWidth,innerHeight]),[420,246]);
    assert.equal(await page.locator('.quota-number').count(),0);
    assert.equal(await page.locator('#energy-target').count(),0);
    assert.equal(await page.locator('video').count(),2,'Only the two character crossfade layers remain');
    assert.equal(await page.locator('body').getAttribute('data-quota-display'),'bars');
    assert.equal(await page.locator('#energy-gauge').count(),0);
    await page.waitForFunction(()=>document.querySelector('#video-a').readyState>=2);
    const video=await page.locator('#video-a').evaluate(v=>({width:v.videoWidth,height:v.videoHeight,fit:getComputedStyle(v).objectFit,src:v.currentSrc}));
    assert.equal(video.width/video.height,4/3); assert.equal(video.fit,'contain');
    assert.match(video.src,/characters\/full\.webm$/);
    assert.deepEqual(await page.locator('.floating-widget').evaluate(e=>[getComputedStyle(e).backgroundColor,getComputedStyle(e).borderWidth]),['rgba(0, 0, 0, 0)','0px']);
    await page.mouse.move(-20,-20); await page.waitForTimeout(180);
    assert.equal(await page.locator('.widget-footer').evaluate(e=>getComputedStyle(e).opacity),'1');
    assert.equal(await page.locator('.widget-footer').evaluate(e=>getComputedStyle(e).pointerEvents),'auto');
    await page.screenshot({path:path.join(output,'floating-transparent-signed-out.png'),omitBackground:true,scale:'css'});
    const pending=app.waitForEvent('window');
    await page.mouse.move(300,110); await page.waitForTimeout(180);
    await page.getByRole('button',{name:'打开设置',exact:true}).click();
    const settings=await pending;
    settings.on('pageerror',e=>errors.push(e.message));
    await settings.locator('#show-codex').waitFor();
    assert.equal(await settings.locator('#energy-target').inputValue(),'codex');
    assert.equal(await settings.locator('#quota-display').inputValue(),'bars');
    assert.equal(await settings.locator('#startup-animation-enabled').count(),0);
    const settingsViewport=await settings.evaluate(()=>[innerWidth,innerHeight]);
    assert(Math.abs(settingsViewport[0]-560)<=4&&Math.abs(settingsViewport[1]-720)<=4);
    await settings.locator('[data-scene=low]').click();
    await page.waitForFunction(()=>document.querySelector('#scene-stage').dataset.state==='low');
    await page.waitForTimeout(400);
    const opacity=await page.locator('.scene-video').evaluateAll(vs=>vs.map(v=>Number(getComputedStyle(v).opacity)));
    assert(opacity.every(v=>v>0&&v<1),`Crossfade: ${opacity}`);
    await page.waitForTimeout(1600);
    await settings.locator('[data-scene=stone]').click();
    await page.waitForFunction(()=>document.querySelector('#scene-stage').dataset.state==='stone');
    await page.waitForTimeout(2000);
    await settings.locator('[data-scene=full]').click();
    await settings.locator('[data-scene=low]').click();
    await settings.locator('[data-scene=stone]').click();
    // Each new alpha clip has a bounded six-second load window. Check the
    // eventual final selection rather than assuming all decoders finish in
    // the same fixed 4.2 seconds, especially while Settings covers the widget.
    await page.waitForTimeout(6100);
    await page.waitForFunction(()=>document.querySelector('#scene-stage').dataset.state==='stone',null,{timeout:8000});
    assert.equal(await page.locator('#scene-stage').getAttribute('data-state'),'stone');
    await settings.locator('#follow-quota').click();
    await page.locator('#preview-badge').waitFor({state:'hidden'});
    await settings.locator('#show-claude').uncheck();
    await page.waitForFunction(()=>document.querySelectorAll('.provider').length===1);
    assert.equal(await page.locator('.provider h3').innerText(),'Codex');
    await settings.locator('#show-codex').uncheck();
    await page.locator('#no-providers').waitFor({state:'visible'});
    await settings.locator('#show-claude').check();
    await page.waitForFunction(()=>document.querySelectorAll('.provider').length===1);
    assert.equal(await page.locator('.provider h3').innerText(),'Claude Code');
    await settings.locator('#show-codex').check();
    await settings.locator('#launch-codex').check();
    await settings.locator('#launch-claude').check();
    await settings.locator('#threshold').selectOption('30');
    let snapshot=await page.evaluate(()=>window.monitor.getSnapshot());
    assert.equal(snapshot.settings.launchWithCodex,true);
    assert.equal(snapshot.settings.launchWithClaude,true);
    assert.equal(snapshot.settings.warningThreshold,30);
    assert.equal(snapshot.energy.scene,'unknown');
    await settings.locator('#launch-codex').uncheck();
    await settings.locator('#launch-claude').uncheck();
    await settings.locator('#threshold').selectOption('20');
    await settings.locator('#floating-scale').selectOption('150');
    await page.waitForTimeout(300);
    const windows=await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().map(w=>({url:w.webContents.getURL(),size:w.getSize(),zoom:w.webContents.getZoomFactor()})));
    const widget=windows.find(w=>w.url.endsWith('/index.html'));
    // At 150% Windows DPI, 369 DIP lands between physical pixels; native
    // window bounds can round back by one DIP while the page zoom stays exact.
    assert.equal(widget.size[0],630);
    assert(Math.abs(widget.size[1]-369)<=1,`Scaled widget height: ${widget.size[1]}`);
    assert.equal(widget.zoom,1.5);
    assert.deepEqual(await settings.evaluate(()=>[innerWidth,innerHeight]),settingsViewport);
    await settings.locator('#floating-scale').selectOption('100');
    await settings.locator('#reduce-motion').check();
    await page.waitForTimeout(100);
    assert.equal(await page.locator('.scene-video.is-visible').evaluate(v=>v.paused),true);
    await settings.locator('#reduce-motion').uncheck();
    const closed=settings.waitForEvent('close');
    await settings.getByRole('button',{name:'完成',exact:true}).click();
    await closed;
    assert.equal(page.isClosed(),false);
    assert.equal(errors.length,0,errors.join('\n'));
    console.log(JSON.stringify({ok:true,checks:['420x246-transparent-character','no-panel-or-frame','persistent-controls','separate-settings-window','alpha-webm-contained','smooth-crossfade','latest-preview-wins','provider-selection','autostart-switches-test-mode','unknown-quota','630x369-independent-scaling','reduced-motion','settings-close-keeps-widget','no-renderer-errors']}));
  } finally { if(app) await app.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
